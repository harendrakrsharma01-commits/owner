<section aria-labelledby="a-intro">
  <h2 id="a-intro">भिन्न क्या है और यह कैलकुलेटर कैसे मदद करता है</h2>
  <p>भिन्न के दो भाग होते हैं: ऊपर का <strong>अंश</strong> बताता है कि हमारे पास कितने भाग हैं, और नीचे का <strong>हर</strong> बताता है कि एक पूरी चीज़ कितने बराबर भागों में बँटी है। यह कैलकुलेटर उचित भिन्न (3/4), विषम भिन्न (7/4), मिश्रित भिन्न (2 1/3), पूर्ण संख्याओं और ऋणात्मक भिन्नों के साथ काम करता है।</p>
  <p>हर उत्तर सटीक होता है। गणना पूर्ण संख्याओं से होती है, गोल किए गए दशमलव से नहीं, इसलिए 1/3 हमेशा 1/3 ही रहता है। दशमलव सिर्फ दिखाने के लिए है, और दशमलव के बाद कितने अंक दिखें, यह आप चुन सकते हैं।</p>
</section>

<section aria-labelledby="a-use">
  <h2 id="a-use">भिन्न कैलकुलेटर का उपयोग कैसे करें</h2>
  <ol>
    <li>पहली भिन्न लिखें: ऊपर वाले खाने में अंश, नीचे वाले में हर। मिश्रित भिन्न के लिए बाईं ओर पूर्ण संख्या भी लिखें।</li>
    <li><strong>+</strong>, <strong>−</strong>, <strong>×</strong> या <strong>÷</strong> चुनें।</li>
    <li>दूसरी भिन्न लिखें और <strong>हल करें</strong> दबाएँ (या Enter)।</li>
    <li>सरलतम भिन्न, मिश्रित भिन्न, दशमलव और प्रतिशत देखें, और नीचे पूरा हल पढ़ें।</li>
  </ol>
  <p>ऊपर के टैब से बाकी टूल खुलते हैं: कई भिन्नें एक साथ, सरल करना, मिश्रित भिन्न, दशमलव, प्रतिशत, तुलना, क्रम, संख्या का भिन्न, “X, Y का कौन-सा भिन्न है?” और तुल्य भिन्नें।</p>
</section>

<section aria-labelledby="a-add">
  <h2 id="a-add">भिन्नों का जोड़</h2>
  <p>जोड़ने से पहले दोनों भिन्नों का हर समान करना होता है। सबसे छोटा समान हर <strong>LCD</strong> कहलाता है, जो हरों का <strong>LCM (लघुत्तम समापवर्त्य)</strong> होता है।</p>
  <div class="fr-callout"><p><strong>उदाहरण: <span dir="ltr">1/2 + 1/3</span></strong></p><ol>
    <li>2 और 3 का LCM = 6</li><li><span dir="ltr">1/2 = 3/6</span> और <span dir="ltr">1/3 = 2/6</span></li><li><span dir="ltr">3/6 + 2/6 = 5/6</span></li><li>5/6 पहले से सरलतम रूप में है।</li></ol></div>
</section>

<section aria-labelledby="a-sub">
  <h2 id="a-sub">भिन्नों का घटाना</h2>
  <p>घटाने में भी पहले हर समान करें, फिर अंश घटाएँ।</p>
  <div class="fr-callout"><p><strong>उदाहरण: <span dir="ltr">3/4 − 1/6</span></strong></p><ol>
    <li>4 और 6 का LCM = 12</li><li><span dir="ltr">3/4 = 9/12</span> और <span dir="ltr">1/6 = 2/12</span></li><li><span dir="ltr">9/12 − 2/12 = 7/12</span></li></ol></div>
  <p>अगर दूसरी भिन्न बड़ी हो तो उत्तर ऋणात्मक आता है: <span dir="ltr">1/4 − 3/4 = −1/2</span>।</p>
</section>

<section aria-labelledby="a-mul">
  <h2 id="a-mul">भिन्नों का गुणा</h2>
  <p>गुणा में समान हर की ज़रूरत नहीं। अंश × अंश और हर × हर करें, फिर सरल करें।</p>
  <div class="fr-callout"><p><strong>उदाहरण: <span dir="ltr">2/3 × 3/4</span></strong></p><ol>
    <li>अंश: 2 × 3 = 6</li><li>हर: 3 × 4 = 12</li><li><span dir="ltr">6/12 = 1/2</span> (HCF 6)</li></ol></div>
</section>

<section aria-labelledby="a-div">
  <h2 id="a-div">भिन्नों का भाग</h2>
  <p>किसी भिन्न से भाग देने के लिए उसके <strong>व्युत्क्रम</strong> (उलटी भिन्न) से गुणा करें।</p>
  <div class="fr-callout"><p><strong>उदाहरण: <span dir="ltr">2/3 ÷ 4/5</span></strong></p><ol>
    <li>4/5 का व्युत्क्रम 5/4</li><li><span dir="ltr">2/3 × 5/4 = 10/12</span></li><li><span dir="ltr">10/12 = 5/6</span> (HCF 2)</li></ol></div>
  <p>शून्य से भाग परिभाषित नहीं है, इसलिए दूसरी भिन्न 0 हो तो कैलकुलेटर रोक देता है। वहीं 0 को किसी भिन्न से भाग देने पर उत्तर 0 ही आता है।</p>
</section>

<section aria-labelledby="a-simp">
  <h2 id="a-simp">भिन्न का सरलीकरण (सरलतम रूप)</h2>
  <p>भिन्न सरलतम रूप में तब होती है जब अंश और हर का 1 के अलावा कोई उभयनिष्ठ गुणनखंड न हो। दोनों को उनके <strong>HCF (महत्तम समापवर्तक)</strong> से भाग दें। “सरल करें” टैब यूक्लिड विधि से HCF निकालकर हर पंक्ति दिखाता है।</p>
  <div class="fr-callout"><p><strong>उदाहरण: 24/36।</strong> 36 = 1 × 24 + 12, 24 = 2 × 12 + 0, इसलिए HCF = 12 और <span dir="ltr">24/36 = 2/3</span>।</p></div>
</section>

<section aria-labelledby="a-mixed">
  <h2 id="a-mixed">मिश्रित भिन्न और विषम भिन्न</h2>
  <p><strong>विषम भिन्न</strong> में अंश, हर के बराबर या उससे बड़ा होता है (7/3)। <strong>मिश्रित भिन्न</strong> उसी मान को पूर्ण संख्या और उचित भिन्न के रूप में लिखती है (2 1/3)।</p>
  <ul>
    <li>मिश्रित → विषम: पूर्ण संख्या × हर + अंश। <span dir="ltr">2 1/3</span> → 2 × 3 + 1 = 7 → 7/3।</li>
    <li>विषम → मिश्रित: भाग दें। 7 ÷ 3 = 2, शेष 1 → <span dir="ltr">2 1/3</span>।</li>
  </ul>
  <p>ऋणात्मक मिश्रित भिन्न में माइनस पूरे मान पर लगता है: <span dir="ltr">−2 1/3 = −7/3</span>। माइनस सिर्फ पूर्ण संख्या वाले खाने में लिखें।</p>
</section>

<section aria-labelledby="a-dec">
  <h2 id="a-dec">भिन्न से दशमलव और दशमलव से भिन्न</h2>
  <p><strong>भिन्न → दशमलव:</strong> अंश को हर से भाग दें। 3/8 = 0.375। सरलतम भिन्न की दशमलव तभी खत्म होती है जब हर के अभाज्य गुणनखंड सिर्फ 2 और 5 हों; नहीं तो अंक दोहराते रहते हैं, जैसे <span dir="ltr">1/6 = 0.1666… = 0.1(6)</span>।</p>
  <p><strong>दशमलव → भिन्न:</strong> दशमलव के बाद के अंक गिनें, संख्या को 10, 100, 1000… पर लिखें और सरल करें। <span dir="ltr">0.75 = 75/100 = 3/4</span>, <span dir="ltr">0.125 = 125/1000 = 1/8</span>। कैलकुलेटर आपकी लिखी दशमलव को ठीक वैसा ही मानता है: 0.333333 का उत्तर 333333/1000000 होगा, 1/3 नहीं। आवर्ती दशमलव के लिए दोहराने वाले अंक कोष्ठक में लिखें: <span dir="ltr">0.(3) = 1/3</span>।</p>
</section>

<section aria-labelledby="a-pct">
  <h2 id="a-pct">भिन्न से प्रतिशत</h2>
  <p>प्रतिशत यानी “सौ में से”। भिन्न को 100 से गुणा करें: <span dir="ltr">1/2 = 50%</span>, <span dir="ltr">3/4 = 75%</span>, <span dir="ltr">1/8 = 12.5%</span>। उलटा करने के लिए प्रतिशत को 100 पर लिखकर सरल करें: <span dir="ltr">12.5% = 12.5/100 = 1/8</span>।</p>
</section>

<section aria-labelledby="a-cmp">
  <h2 id="a-cmp">भिन्नों की तुलना और क्रम</h2>
  <p>कौन-सी भिन्न बड़ी है, यह जानने के लिए <strong>तिरछा गुणा</strong> करें: 2/3 और 3/5 में 2 × 5 = 10 और 3 × 3 = 9, इसलिए <span dir="ltr">2/3 &gt; 3/5</span>। दोनों को LCD पर लिखकर भी देख सकते हैं (10/15 और 9/15)। “तुलना” और “क्रम में लगाएँ” टैब गोल किए दशमलव नहीं, बल्कि सटीक तिरछे गुणा का उपयोग करते हैं, इसलिए आरोही और अवरोही क्रम हमेशा सही आता है।</p>
</section>

<section aria-labelledby="a-eq">
  <h2 id="a-eq">तुल्य भिन्नें</h2>
  <p>अंश और हर को एक ही संख्या से गुणा करने पर तुल्य भिन्न मिलती है — मात्रा वही, बस भाग ज़्यादा: <span dir="ltr">1/2 = 2/4 = 3/6 = 4/8 = 5/10</span>। सरल करना इसका उलटा है।</p>
</section>

<section aria-labelledby="a-of">
  <h2 id="a-of">किसी संख्या का भिन्न निकालना</h2>
  <p>“का” का मतलब गुणा है: <span dir="ltr">80 का 3/4 = 3/4 × 80 = 240/4 = 60</span>। उलटा सवाल — “15, 60 का कौन-सा भिन्न है?” — भाग से हल होता है: <span dir="ltr">15/60 = 1/4 = 25%</span>।</p>
</section>

<section aria-labelledby="a-lcd">
  <h2 id="a-lcd">LCD, HCF और LCM</h2>
  <ul>
    <li><strong>HCF / GCD</strong> (महत्तम समापवर्तक) — दोनों संख्याओं को पूरा भाग देने वाली सबसे बड़ी संख्या। सरल करने में काम आता है।</li>
    <li><strong>LCM</strong> (लघुत्तम समापवर्त्य) — वह सबसे छोटी संख्या जिसे दोनों पूरा भाग दें। हरों का LCM ही <strong>LCD</strong> है, जो जोड़, घटाना और तुलना में काम आता है।</li>
  </ul>
  <p>इनका संबंध: LCM(a, b) = a × b ÷ HCF(a, b)। 4 और 6 के लिए HCF = 2, इसलिए LCM = 24 ÷ 2 = 12।</p>
</section>

<section aria-labelledby="a-mist">
  <h2 id="a-mist">भिन्नों में होने वाली आम गलतियाँ</h2>
  <ul>
    <li>हरों को जोड़ देना: <span dir="ltr">1/2 + 1/3</span> का उत्तर 2/5 नहीं है।</li>
    <li>भाग में दूसरी भिन्न को उलटना भूल जाना।</li>
    <li>उत्तर को सरल न करना, जैसे 1/2 की जगह 6/12 लिखना।</li>
    <li><span dir="ltr">−2 1/3</span> को −2 + 1/3 समझना। इसका मतलब −(2 + 1/3) = −7/3 है।</li>
    <li>सिर्फ हर देखकर तुलना करना: 3/5, 1/2 से बड़ी है, भले 5 बड़ा हर है।</li>
  </ul>
</section>
