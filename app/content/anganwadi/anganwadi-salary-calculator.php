  <p>जब सरकार मानदेय बढ़ाती है, तो नई दर अक्सर किसी पिछले महीने से लागू होती है, जबकि भुगतान बाद में शुरू होता है। बीच के महीनों का अंतर एरियर (बकाया) कहलाता है:</p>
