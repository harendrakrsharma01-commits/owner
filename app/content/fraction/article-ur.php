<section aria-labelledby="a-intro">
  <h2 id="a-intro">کسر کیا ہے اور یہ کیلکولیٹر کیسے مدد کرتا ہے</h2>
  <p>کسر کے دو حصے ہوتے ہیں: اوپر والا <strong>شمار کنندہ</strong> بتاتا ہے کہ ہمارے پاس کتنے حصے ہیں، اور نیچے والا <strong>نسب نما</strong> بتاتا ہے کہ ایک مکمل چیز کتنے برابر حصوں میں تقسیم ہے۔ یہ کیلکولیٹر واجب کسر (<span dir="ltr">3/4</span>)، غیر واجب کسر (<span dir="ltr">7/4</span>)، مخلوط کسر (<span dir="ltr">2 1/3</span>)، مکمل اعداد اور منفی کسور کے ساتھ کام کرتا ہے۔</p>
  <p>ہر جواب بالکل درست ہوتا ہے۔ حساب مکمل اعداد سے کیا جاتا ہے، گول کیے گئے اعشاریہ سے نہیں، اس لیے <span dir="ltr">1/3</span> ہمیشہ <span dir="ltr">1/3</span> ہی رہتا ہے۔ اعشاریہ صرف دکھانے کے لیے ہے، اور اعشاریہ کے بعد کتنے ہندسے دکھیں یہ آپ خود چن سکتے ہیں۔</p>
</section>

<section aria-labelledby="a-use">
  <h2 id="a-use">کسر کیلکولیٹر کیسے استعمال کریں</h2>
  <ol>
    <li>پہلا کسر لکھیں: اوپر والے خانے میں شمار کنندہ، نیچے والے میں نسب نما۔ مخلوط کسر کے لیے بائیں طرف مکمل عدد بھی لکھیں۔</li>
    <li><strong>+</strong>، <strong>−</strong>، <strong>×</strong> یا <strong>÷</strong> منتخب کریں۔</li>
    <li>دوسرا کسر لکھیں اور <strong>حل کریں</strong> دبائیں (یا Enter)۔</li>
    <li>آسان ترین کسر، مخلوط کسر، اعشاریہ اور فیصد دیکھیں، اور نیچے مکمل حل پڑھیں۔</li>
  </ol>
  <p>اوپر کے ٹیب سے باقی ٹول کھلتے ہیں: کئی کسور ایک ساتھ، آسان کرنا، مخلوط کسر، اعشاریہ، فیصد، موازنہ، ترتیب، عدد کا کسر، “X، Y کا کون سا کسر ہے؟” اور مساوی کسور۔</p>
</section>

<section aria-labelledby="a-add">
  <h2 id="a-add">کسور کی جمع</h2>
  <p>جمع سے پہلے دونوں کسور کا نسب نما برابر کرنا ضروری ہے۔ سب سے چھوٹا مشترک نسب نما <strong>LCD</strong> کہلاتا ہے، جو نسب نماؤں کا <strong>ذو اضعافِ اقل (LCM)</strong> ہوتا ہے۔</p>
  <div class="fr-callout"><p><strong>مثال: <span dir="ltr">1/2 + 1/3</span></strong></p><ol>
    <li>2 اور 3 کا LCM = 6</li><li><span dir="ltr">1/2 = 3/6</span> اور <span dir="ltr">1/3 = 2/6</span></li><li><span dir="ltr">3/6 + 2/6 = 5/6</span></li><li><span dir="ltr">5/6</span> پہلے سے آسان ترین شکل میں ہے۔</li></ol></div>
</section>

<section aria-labelledby="a-sub">
  <h2 id="a-sub">کسور کی تفریق</h2>
  <p>تفریق میں بھی پہلے نسب نما برابر کریں، پھر شمار کنندے تفریق کریں۔</p>
  <div class="fr-callout"><p><strong>مثال: <span dir="ltr">3/4 − 1/6</span></strong></p><ol>
    <li>4 اور 6 کا LCM = 12</li><li><span dir="ltr">3/4 = 9/12</span> اور <span dir="ltr">1/6 = 2/12</span></li><li><span dir="ltr">9/12 − 2/12 = 7/12</span></li></ol></div>
  <p>اگر دوسرا کسر بڑا ہو تو جواب منفی آتا ہے: <span dir="ltr">1/4 − 3/4 = −1/2</span>۔</p>
</section>

<section aria-labelledby="a-mul">
  <h2 id="a-mul">کسور کی ضرب</h2>
  <p>ضرب میں مشترک نسب نما کی ضرورت نہیں۔ شمار کنندہ × شمار کنندہ اور نسب نما × نسب نما کریں، پھر آسان کریں۔</p>
  <div class="fr-callout"><p><strong>مثال: <span dir="ltr">2/3 × 3/4</span></strong></p><ol>
    <li>شمار کنندے: <span dir="ltr">2 × 3 = 6</span></li><li>نسب نما: <span dir="ltr">3 × 4 = 12</span></li><li><span dir="ltr">6/12 = 1/2</span> (عادِ اعظم 6)</li></ol></div>
</section>

<section aria-labelledby="a-div">
  <h2 id="a-div">کسور کی تقسیم</h2>
  <p>کسی کسر سے تقسیم کرنے کے لیے اس کے <strong>مقلوب</strong> (الٹے کسر) سے ضرب دیں۔</p>
  <div class="fr-callout"><p><strong>مثال: <span dir="ltr">2/3 ÷ 4/5</span></strong></p><ol>
    <li><span dir="ltr">4/5</span> کا مقلوب <span dir="ltr">5/4</span></li><li><span dir="ltr">2/3 × 5/4 = 10/12</span></li><li><span dir="ltr">10/12 = 5/6</span> (عادِ اعظم 2)</li></ol></div>
  <p>صفر سے تقسیم کی تعریف نہیں، اس لیے دوسرا کسر صفر ہو تو کیلکولیٹر روک دیتا ہے۔ صفر کو کسی کسر سے تقسیم کریں تو جواب صفر ہی آتا ہے۔</p>
</section>

<section aria-labelledby="a-simp">
  <h2 id="a-simp">کسر کو آسان کرنا</h2>
  <p>کسر آسان ترین شکل میں تب ہوتا ہے جب شمار کنندہ اور نسب نما کا 1 کے سوا کوئی مشترک جزو نہ ہو۔ دونوں کو ان کے <strong>عادِ اعظم (HCF)</strong> سے تقسیم کریں۔ “آسان کریں” ٹیب اقلیدس کے طریقے سے عادِ اعظم نکال کر ہر سطر دکھاتا ہے۔</p>
  <div class="fr-callout"><p><strong>مثال: <span dir="ltr">24/36</span>۔</strong> <span dir="ltr">36 = 1 × 24 + 12</span>، <span dir="ltr">24 = 2 × 12 + 0</span>، اس لیے عادِ اعظم = 12 اور <span dir="ltr">24/36 = 2/3</span>۔</p></div>
</section>

<section aria-labelledby="a-mixed">
  <h2 id="a-mixed">مخلوط کسر اور غیر واجب کسر</h2>
  <p><strong>غیر واجب کسر</strong> میں شمار کنندہ، نسب نما کے برابر یا اس سے بڑا ہوتا ہے (<span dir="ltr">7/3</span>)۔ <strong>مخلوط کسر</strong> اسی قیمت کو مکمل عدد اور واجب کسر کی صورت میں لکھتا ہے (<span dir="ltr">2 1/3</span>)۔</p>
  <ul>
    <li>مخلوط ← غیر واجب: مکمل عدد × نسب نما + شمار کنندہ۔ <span dir="ltr">2 1/3 → 2 × 3 + 1 = 7 → 7/3</span>۔</li>
    <li>غیر واجب ← مخلوط: تقسیم کریں۔ <span dir="ltr">7 ÷ 3 = 2</span>، باقی 1 ← <span dir="ltr">2 1/3</span>۔</li>
  </ul>
  <p>منفی مخلوط کسر میں منفی کا نشان پوری قیمت پر لگتا ہے: <span dir="ltr">−2 1/3 = −7/3</span>۔ منفی کا نشان صرف مکمل عدد والے خانے میں لکھیں۔</p>
</section>

<section aria-labelledby="a-dec">
  <h2 id="a-dec">کسر سے اعشاریہ اور اعشاریہ سے کسر</h2>
  <p><strong>کسر ← اعشاریہ:</strong> شمار کنندہ کو نسب نما سے تقسیم کریں۔ <span dir="ltr">3/8 = 0.375</span>۔ آسان ترین کسر کا اعشاریہ تبھی ختم ہوتا ہے جب نسب نما کے مفرد اجزائے ضربی صرف 2 اور 5 ہوں؛ ورنہ ہندسے دہراتے رہتے ہیں، جیسے <span dir="ltr">1/6 = 0.1666… = 0.1(6)</span>۔</p>
  <p><strong>اعشاریہ ← کسر:</strong> اعشاریہ کے بعد ہندسے گنیں، عدد کو 10، 100، 1000… پر لکھیں اور آسان کریں: <span dir="ltr">0.75 = 75/100 = 3/4</span>، <span dir="ltr">0.125 = 125/1000 = 1/8</span>۔ کیلکولیٹر آپ کا لکھا ہوا اعشاریہ بالکل ویسا ہی مانتا ہے: <span dir="ltr">0.333333</span> کا جواب <span dir="ltr">333333/1000000</span> ہوگا، <span dir="ltr">1/3</span> نہیں۔ دہرانے والے اعشاریہ کے لیے دہرانے والے ہندسے قوسین میں لکھیں: <span dir="ltr">0.(3) = 1/3</span>۔</p>
</section>

<section aria-labelledby="a-pct">
  <h2 id="a-pct">کسر سے فیصد</h2>
  <p>فیصد کا مطلب ہے “سو میں سے”۔ کسر کو 100 سے ضرب دیں: <span dir="ltr">1/2 = 50%</span>، <span dir="ltr">3/4 = 75%</span>، <span dir="ltr">1/8 = 12.5%</span>۔ الٹا کرنے کے لیے فیصد کو 100 پر لکھ کر آسان کریں: <span dir="ltr">12.5% = 12.5/100 = 1/8</span>۔</p>
</section>

<section aria-labelledby="a-cmp">
  <h2 id="a-cmp">کسور کا موازنہ اور ترتیب</h2>
  <p>کون سا کسر بڑا ہے، یہ جاننے کے لیے <strong>کراس ضرب</strong> کریں: <span dir="ltr">2/3</span> اور <span dir="ltr">3/5</span> میں <span dir="ltr">2 × 5 = 10</span> اور <span dir="ltr">3 × 3 = 9</span>، اس لیے <span dir="ltr">2/3 &gt; 3/5</span>۔ دونوں کو LCD پر لکھ کر بھی دیکھ سکتے ہیں (<span dir="ltr">10/15</span> اور <span dir="ltr">9/15</span>)۔ “موازنہ” اور “ترتیب” ٹیب گول کیے اعشاریہ کے بجائے درست کراس ضرب استعمال کرتے ہیں۔</p>
</section>

<section aria-labelledby="a-eq">
  <h2 id="a-eq">مساوی کسور</h2>
  <p>شمار کنندہ اور نسب نما کو ایک ہی عدد سے ضرب دینے پر مساوی کسر ملتا ہے — مقدار وہی، بس حصے زیادہ: <span dir="ltr">1/2 = 2/4 = 3/6 = 4/8 = 5/10</span>۔ آسان کرنا اس کا الٹ ہے۔</p>
</section>

<section aria-labelledby="a-of">
  <h2 id="a-of">کسی عدد کا کسر نکالنا</h2>
  <p>“کا” کا مطلب ضرب ہے: <span dir="ltr">3/4 × 80 = 240/4 = 60</span>، یعنی 80 کا <span dir="ltr">3/4</span> برابر ہے 60 کے۔ الٹا سوال — “15، 60 کا کون سا کسر ہے؟” — تقسیم سے حل ہوتا ہے: <span dir="ltr">15/60 = 1/4 = 25%</span>۔</p>
</section>

<section aria-labelledby="a-lcd">
  <h2 id="a-lcd">LCD، عادِ اعظم اور ذو اضعافِ اقل</h2>
  <ul>
    <li><strong>عادِ اعظم (HCF / GCD)</strong> — وہ سب سے بڑا عدد جو دونوں اعداد کو پورا تقسیم کرے۔ آسان کرنے میں کام آتا ہے۔</li>
    <li><strong>ذو اضعافِ اقل (LCM)</strong> — وہ سب سے چھوٹا عدد جسے دونوں پورا تقسیم کریں۔ نسب نماؤں کا LCM ہی <strong>LCD</strong> ہے، جو جمع، تفریق اور موازنے میں کام آتا ہے۔</li>
  </ul>
  <p>ان کا تعلق: <span dir="ltr">LCM(a, b) = a × b ÷ HCF(a, b)</span>۔ 4 اور 6 کے لیے عادِ اعظم = 2، اس لیے <span dir="ltr">LCM = 24 ÷ 2 = 12</span>۔</p>
</section>

<section aria-labelledby="a-mist">
  <h2 id="a-mist">کسور میں عام غلطیاں</h2>
  <ul>
    <li>نسب نماؤں کو جمع کر دینا: <span dir="ltr">1/2 + 1/3</span> کا جواب <span dir="ltr">2/5</span> نہیں ہے۔</li>
    <li>تقسیم میں دوسرے کسر کو الٹنا بھول جانا۔</li>
    <li>جواب کو آسان نہ کرنا، جیسے <span dir="ltr">1/2</span> کی جگہ <span dir="ltr">6/12</span> لکھنا۔</li>
    <li><span dir="ltr">−2 1/3</span> کو <span dir="ltr">−2 + 1/3</span> سمجھنا۔ اس کا مطلب <span dir="ltr">−(2 + 1/3) = −7/3</span> ہے۔</li>
    <li>صرف نسب نما دیکھ کر موازنہ کرنا: <span dir="ltr">3/5</span>، <span dir="ltr">1/2</span> سے بڑا ہے، چاہے 5 بڑا نسب نما ہے۔</li>
  </ul>
</section>
