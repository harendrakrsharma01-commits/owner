<section aria-labelledby="b-how">
  <h2 id="b-how">How the birthday countdown works</h2>
  <p>The countdown compares two calendar dates: the “as of” date (today, unless you change it) and the next date your birthday falls on. The difference is the number of days to go. Because it is a date difference rather than a clock, it doesn’t tick down during the day and isn’t affected by daylight-saving changes; it moves by one at midnight on your device.</p>
  <ul>
    <li><strong>Days until birthday</strong> — “1” means tomorrow. On the birthday itself the calculator shows “today” and starts counting to the next one.</li>
    <li><strong>Weeks + days</strong> — the same span in completed weeks and leftover days, handy for planning a party or a gift.</li>
    <li><strong>Turning</strong> — the age reached on that birthday.</li>
    <li><strong>Weekday</strong> — the day of the week the birthday lands on. It moves forward one weekday a year, or two after a 29 February.</li>
  </ul>
  <p>The table under the ring lists your previous birthday, this year’s and next year’s, with the age turned and how far each is from the as-of date.</p>
</section>

<section aria-labelledby="b-ex">
  <h2 id="b-ex">Example</h2>
  <p>For a birthday of 24 September 2000, viewed on 26 September 2026, the birthday was two days ago. The next one is Friday, 24 September 2027 — 363 days away, or 51 weeks and 6 days — when the person turns 27. Birthdays after that fall on a Sunday in 2028 (a leap year pushes it on two days), then Monday 2029 and Tuesday 2030.</p>
</section>

<section aria-labelledby="b-leap">
  <h2 id="b-leap">Birthdays on 29 February</h2>
  <p>If you were born on 29 February, your birthday appears on that date in leap years. In other years the calculator shows it on 28 February by default; switch the rule to “Next day (Mar 1)” if you mark it on 1 March. A note in the results explains which day is being used, and your date of birth itself is never altered. Some laws specify one day for legal purposes — Scotland’s Age of Legal Capacity Act 1991, for example, uses 1 March — but that is a legal-age rule, not a rule about when you celebrate.</p>
</section>

