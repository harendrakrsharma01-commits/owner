<section aria-labelledby="a-intro">
  <h2 id="a-intro">Что умеет калькулятор дробей</h2>
  <p>У обыкновенной дроби две части: <strong>знаменатель</strong> (нижнее число) показывает, на сколько равных частей разделили целое, а <strong>числитель</strong> (верхнее число) — сколько таких частей взяли. Калькулятор работает с правильными дробями (3/4), неправильными дробями (7/4), смешанными числами (2 1/3), целыми и отрицательными числами.</p>
  <p>Ответ всегда точный. Все действия выполняются с целыми числами, без округлённых десятичных дробей, поэтому 1/3 остаётся 1/3, а большие числители и знаменатели не теряют точности. Десятичная запись нужна только для показа, число знаков после запятой вы выбираете сами.</p>
</section>

<section aria-labelledby="a-use">
  <h2 id="a-use">Как пользоваться калькулятором</h2>
  <ol>
    <li>Введите первую дробь: в верхнее поле — числитель, в нижнее — знаменатель. Для смешанного числа заполните и поле целой части слева.</li>
    <li>Выберите действие: <strong>+</strong>, <strong>−</strong>, <strong>×</strong> или <strong>÷</strong>.</li>
    <li>Введите вторую дробь и нажмите <strong>Решить</strong> (или Enter).</li>
    <li>Посмотрите несократимую дробь, смешанное число, десятичную дробь и проценты, а ниже — пошаговое решение.</li>
  </ol>
  <p>Вкладки над калькулятором открывают другие режимы: несколько дробей сразу, сокращение, смешанные числа, десятичные дроби, проценты, сравнение, упорядочивание, дробь от числа, «какую часть составляет X от Y» и равные дроби.</p>
</section>

<section aria-labelledby="a-add">
  <h2 id="a-add">Сложение дробей</h2>
  <p>Складывать можно только доли одинакового размера, поэтому дроби сначала приводят к <strong>общему знаменателю</strong>. Наименьший общий знаменатель — это <strong>НОК</strong> знаменателей.</p>
  <div class="fr-callout"><p><strong>Пример: <span dir="ltr">1/2 + 1/3</span></strong></p><ol>
    <li>НОК(2, 3) = 6</li><li><span dir="ltr">1/2 = 3/6</span>, <span dir="ltr">1/3 = 2/6</span></li><li><span dir="ltr">3/6 + 2/6 = 5/6</span></li><li>Дробь 5/6 несократимая.</li></ol></div>
</section>

<section aria-labelledby="a-sub">
  <h2 id="a-sub">Вычитание дробей</h2>
  <p>Вычитание выполняется так же: приводим к общему знаменателю и вычитаем числители.</p>
  <div class="fr-callout"><p><strong>Пример: <span dir="ltr">3/4 − 1/6</span></strong></p><ol>
    <li>НОК(4, 6) = 12</li><li><span dir="ltr">3/4 = 9/12</span>, <span dir="ltr">1/6 = 2/12</span></li><li><span dir="ltr">9/12 − 2/12 = 7/12</span></li></ol></div>
  <p>Если вычитаемое больше, ответ отрицательный: <span dir="ltr">1/4 − 3/4 = −1/2</span>.</p>
</section>

<section aria-labelledby="a-mul">
  <h2 id="a-mul">Умножение дробей</h2>
  <p>Общий знаменатель не нужен: перемножаем числители, перемножаем знаменатели и сокращаем.</p>
  <div class="fr-callout"><p><strong>Пример: <span dir="ltr">2/3 × 3/4</span></strong></p><ol>
    <li>Числители: 2 × 3 = 6</li><li>Знаменатели: 3 × 4 = 12</li><li><span dir="ltr">6/12 = 1/2</span> (НОД 6)</li></ol></div>
</section>

<section aria-labelledby="a-div">
  <h2 id="a-div">Деление дробей</h2>
  <p>Чтобы разделить на дробь, нужно умножить на <strong>обратную дробь</strong> (перевернуть делитель).</p>
  <div class="fr-callout"><p><strong>Пример: <span dir="ltr">2/3 ÷ 4/5</span></strong></p><ol>
    <li>Дробь, обратная 4/5, — это 5/4</li><li><span dir="ltr">2/3 × 5/4 = 10/12</span></li><li><span dir="ltr">10/12 = 5/6</span> (НОД 2)</li></ol></div>
  <p>Делить на ноль нельзя, поэтому калькулятор не даст разделить на дробь, равную нулю. Ноль, делённый на дробь, равен нулю.</p>
</section>

<section aria-labelledby="a-simp">
  <h2 id="a-simp">Сокращение дробей</h2>
  <p>Дробь <strong>несократимая</strong>, если у числителя и знаменателя нет общих делителей, кроме 1. Чтобы сократить дробь, разделите обе части на их <strong>НОД</strong> — наибольший общий делитель. Во вкладке «Сокращение» НОД находится алгоритмом Евклида, и каждая строка показывается.</p>
  <div class="fr-callout"><p><strong>Пример: 24/36.</strong> 36 = 1 × 24 + 12, 24 = 2 × 12 + 0, значит НОД = 12 и <span dir="ltr">24/36 = 2/3</span>.</p></div>
</section>

<section aria-labelledby="a-mixed">
  <h2 id="a-mixed">Смешанные числа и неправильные дроби</h2>
  <p>В <strong>неправильной дроби</strong> числитель не меньше знаменателя (7/3). <strong>Смешанное число</strong> записывает то же значение как целую часть и правильную дробь: 2 1/3 («две целых одна третья»).</p>
  <ul>
    <li>Смешанное → неправильная: целая часть × знаменатель + числитель. 2 1/3 → 2 × 3 + 1 = 7 → 7/3.</li>
    <li>Неправильная → смешанное: деление с остатком. 7 : 3 = 2 (ост. 1) → 2 1/3.</li>
  </ul>
  <p>Минус у смешанного числа относится ко всему числу: <span dir="ltr">−2 1/3 = −7/3</span>. Ставьте минус только в поле целой части.</p>
</section>

<section aria-labelledby="a-dec">
  <h2 id="a-dec">Перевод дроби в десятичную и обратно</h2>
  <p><strong>Обыкновенная → десятичная:</strong> делим числитель на знаменатель. 3/8 = 0,375. Несократимая дробь даёт конечную десятичную дробь только тогда, когда в разложении знаменателя нет простых множителей, кроме 2 и 5; иначе получается периодическая дробь: <span dir="ltr">1/6 = 0,1666… = 0,1(6)</span>.</p>
  <p><strong>Десятичная → обыкновенная:</strong> записываем цифры над 10, 100, 1000… по числу знаков после запятой и сокращаем: <span dir="ltr">0,75 = 75/100 = 3/4</span>, <span dir="ltr">0,125 = 125/1000 = 1/8</span>. Калькулятор считает введённое число ровно таким, как оно записано: 0,333333 даст 333333/1000000, а не 1/3. Периодическую дробь вводите с периодом в скобках: <span dir="ltr">0,(3) = 1/3</span>. Можно писать и запятую, и точку.</p>
</section>

<section aria-labelledby="a-pct">
  <h2 id="a-pct">Перевод дроби в проценты</h2>
  <p>Процент — это сотая часть. Умножьте дробь на 100: <span dir="ltr">1/2 = 50 %</span>, <span dir="ltr">3/4 = 75 %</span>, <span dir="ltr">1/8 = 12,5 %</span>. Обратно — запишите проценты над 100 и сократите: <span dir="ltr">12,5 % = 12,5/100 = 1/8</span>.</p>
</section>

<section aria-labelledby="a-cmp">
  <h2 id="a-cmp">Сравнение и упорядочивание дробей</h2>
  <p>Удобнее всего сравнивать <strong>перекрёстным умножением</strong>: для 2/3 и 3/5 получаем 2 × 5 = 10 и 3 × 3 = 9, значит <span dir="ltr">2/3 &gt; 3/5</span>. Можно и привести к общему знаменателю: 10/15 и 9/15. Вкладки «Сравнение» и «Упорядочить» сравнивают дроби точно, а не по округлённым десятичным значениям, поэтому порядок по возрастанию и по убыванию всегда верный.</p>
</section>

<section aria-labelledby="a-eq">
  <h2 id="a-eq">Равные дроби</h2>
  <p>Основное свойство дроби: если числитель и знаменатель умножить на одно и то же число, получится равная дробь: <span dir="ltr">1/2 = 2/4 = 3/6 = 4/8 = 5/10</span>. Сокращение — то же свойство в обратную сторону.</p>
</section>

<section aria-labelledby="a-of">
  <h2 id="a-of">Нахождение дроби от числа</h2>
  <p>Чтобы найти дробь от числа, число умножают на дробь: <span dir="ltr">3/4 от 80 = 3/4 × 80 = 240/4 = 60</span>. Обратная задача — «какую часть 15 составляет от 60» — решается делением: <span dir="ltr">15/60 = 1/4 = 25 %</span>.</p>
</section>

<section aria-labelledby="a-lcd">
  <h2 id="a-lcd">НОД, НОК и общий знаменатель</h2>
  <ul>
    <li><strong>НОД</strong> — наибольший общий делитель: самое большое число, на которое делятся оба числа. Нужен для сокращения.</li>
    <li><strong>НОК</strong> — наименьшее общее кратное: самое маленькое число, которое делится на оба числа. НОК знаменателей — это наименьший общий знаменатель для сложения, вычитания и сравнения.</li>
  </ul>
  <p>Они связаны формулой НОК(a, b) = a × b : НОД(a, b). Для 4 и 6: НОД = 2, НОК = 24 : 2 = 12.</p>
</section>

<section aria-labelledby="a-mist">
  <h2 id="a-mist">Типичные ошибки</h2>
  <ul>
    <li>Сложение знаменателей: <span dir="ltr">1/2 + 1/3</span> не равно 2/5.</li>
    <li>При делении забывают перевернуть вторую дробь.</li>
    <li>Ответ не сокращён: 6/12 вместо 1/2.</li>
    <li><span dir="ltr">−2 1/3</span> понимают как −2 + 1/3, а это −(2 + 1/3) = −7/3.</li>
    <li>Сравнивают только знаменатели: 3/5 больше 1/2, хотя знаменатель 5 больше.</li>
  </ul>
</section>
